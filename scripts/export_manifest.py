"""Export the live command catalog to ``manifest.json`` + ``docs/TOOLS.md``.

Run inside QGIS's Python (accurate inspect-based parameters):

    "C:\\Program Files\\QGIS 3.44.15\\bin\\python-qgis-ltr.bat" scripts/export_manifest.py

Writes:
    mcp/piterm_qgis_mcp/manifest.json   (tool catalog bundled with the MCP server)
    docs/TOOLS.md                       (human reference, generated - never edited)
    verification/manifest.json          (copy for the evidence folder)
"""

from __future__ import annotations

import json
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    sys.path.insert(0, os.path.join(ROOT, "plugin"))
    from qgis.core import Qgis, QgsApplication

    app_name = ("QGIS4-piterm-manifest" if Qgis.QGIS_VERSION_INT >= 40000
                else "QGIS3-piterm-manifest")
    QgsApplication.setOrganizationName("QGIS")
    QgsApplication.setOrganizationDomain("qgis.org")
    QgsApplication.setApplicationName(app_name)
    app = QgsApplication([], False)
    app.setApplicationName(app_name)
    app.initQgis()
    try:
        import piterm_qgis_ai.handlers  # noqa: F401  (import registers commands)
        from piterm_qgis_ai.constants import PLUGIN_VERSION
        from piterm_qgis_ai.registry import catalog, command_count

        commands = catalog(with_params=True)
        manifest = {
            "generated": time.strftime("%Y-%m-%d %H:%M:%S"),
            "qgis": Qgis.QGIS_VERSION,
            "plugin_version": PLUGIN_VERSION,
            "count": len(commands),
            "commands": commands,
        }
        out_manifest = os.path.join(ROOT, "mcp", "piterm_qgis_mcp", "manifest.json")
        with open(out_manifest, "w", encoding="utf-8") as fh:
            json.dump(manifest, fh, ensure_ascii=False, indent=1)
        evidence = os.path.join(ROOT, "verification", "manifest.json")
        os.makedirs(os.path.dirname(evidence), exist_ok=True)
        with open(evidence, "w", encoding="utf-8") as fh:
            json.dump(manifest, fh, ensure_ascii=False, indent=1)
        with open(os.path.join(ROOT, "docs", "TOOLS.md"), "w",
                  encoding="utf-8") as fh:
            fh.write(render_tools_md(manifest))
        print("manifest: %d commands -> %s" % (command_count(), out_manifest))
        print("docs/TOOLS.md written")
        return 0
    finally:
        app.exitQgis()


def render_tools_md(manifest):
    lines = [
        "# Piterm QGIS AI - command reference (generated)",
        "",
        "> Generated by `scripts/export_manifest.py` from the live plugin "
        "registry on %s (QGIS %s, plugin %s). **Do not edit by hand.**"
        % (manifest["generated"], manifest["qgis"], manifest["plugin_version"]),
        "",
        "Total commands: **%d**. Risk levels: `read` (safe), `write` (mutates "
        "state), `destructive` (data loss possible), `execute` (runs algorithms "
        "or code)." % manifest["count"],
        "",
    ]
    groups = {}
    for command in manifest["commands"]:
        tags = command.get("tags") or ["misc"]
        groups.setdefault(tags[0], []).append(command)
    lines.append("## Index")
    lines.append("")
    for tag in sorted(groups):
        lines.append("- [%s](#%s) (%d)" % (tag, tag.replace("_", "-"),
                                           len(groups[tag])))
    lines.append("")
    for tag in sorted(groups):
        lines.append("## %s" % tag)
        lines.append("")
        lines.append("| Command | Risk | Parameters | Summary |")
        lines.append("|---|---|---|---|")
        for command in sorted(groups[tag], key=lambda c: c["name"]):
            params = ", ".join(
                ("%s%s" % (p["name"], "" if p.get("required", True) else "?"))
                for p in command.get("params") or []) or "-"
            lines.append("| `%s` | %s | %s | %s |" % (
                command["name"], command.get("risk", ""), params,
                (command.get("summary") or "").replace("|", "\\|")))
        lines.append("")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.exit(main())
